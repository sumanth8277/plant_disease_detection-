-- ==============================================================================
-- Plant Disease Detection and Smart Pesticide & Fertilizer Recommendation System
-- Relational Database Schema (MySQL 8.0+ / utf8mb4 / InnoDB)
-- ==============================================================================

-- 1. Database Initialization (Idempotent)
CREATE DATABASE IF NOT EXISTS plant_disease_db
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE plant_disease_db;

-- ==============================================================================
