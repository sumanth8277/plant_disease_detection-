-- ==============================================================================
-- Table A: users
-- Stores registered users. Anonymous predictions are supported by allowing
-- nullable foreign keys in the predictions table.
-- ==============================================================================
CREATE TABLE IF NOT EXISTS users (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(191) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_email_not_empty CHECK (CHAR_LENGTH(TRIM(email)) > 0),
    CONSTRAINT chk_users_name_not_empty CHECK (CHAR_LENGTH(TRIM(name)) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX idx_users_email ON users(email);


-- ==============================================================================
-- Table B: predictions
-- Stores plant disease diagnosis predictions generated by the AI/ML pipeline.
-- Foreign key references users.id; if user is deleted, prediction history is
-- retained with user_id SET NULL for anonymous research auditing.
-- ==============================================================================
CREATE TABLE IF NOT EXISTS predictions (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT UNSIGNED NULL,
    image_path VARCHAR(255) NOT NULL,
    crop_name VARCHAR(100) NOT NULL,
    disease_code VARCHAR(100) NOT NULL,
    disease_name VARCHAR(150) NOT NULL,
    confidence DECIMAL(5, 4) NOT NULL,
    model_version VARCHAR(50) NOT NULL DEFAULT 'v1.0',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_predictions_user_id
        FOREIGN KEY (user_id) REFERENCES users(id)
        ON DELETE SET NULL
        ON UPDATE CASCADE,
    CONSTRAINT chk_predictions_confidence
        CHECK (confidence >= 0.0000 AND confidence <= 1.0000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX idx_predictions_user_id ON predictions(user_id);
CREATE INDEX idx_predictions_created_at ON predictions(created_at);
CREATE INDEX idx_predictions_crop_disease ON predictions(crop_name, disease_code);


-- ==============================================================================
-- Table C: disease_recommendations
-- Stores vetted educational and advisory guidance for plant diseases.
-- Disease codes serve as unique stable identifiers linked to ML classifications.
-- ==============================================================================
CREATE TABLE IF NOT EXISTS disease_recommendations (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    disease_code VARCHAR(100) NOT NULL UNIQUE,
    crop_name VARCHAR(100) NOT NULL,
    disease_name VARCHAR(150) NOT NULL,
    symptoms TEXT NOT NULL,
    treatment_guidance TEXT NOT NULL,
    prevention_guidance TEXT NOT NULL,
    source_reference VARCHAR(255) NULL,
    review_status ENUM('draft', 'educational_only', 'expert_reviewed', 'verified')
        NOT NULL DEFAULT 'educational_only',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX idx_disease_crop_name ON disease_recommendations(crop_name);
CREATE INDEX idx_disease_code ON disease_recommendations(disease_code);


-- ==============================================================================
-- Table D: fertilizer_recommendations
-- Stores crop nutrition and fertilizer advisory guidance based on growth stages
-- and soil/nutrient context. Multiple recommendations per crop are allowed.
-- ==============================================================================
CREATE TABLE IF NOT EXISTS fertilizer_recommendations (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    crop_name VARCHAR(100) NOT NULL,
    growth_stage VARCHAR(100) NULL,
    soil_condition VARCHAR(255) NULL,
    recommendation_text TEXT NOT NULL,
    source_reference VARCHAR(255) NULL,
    review_status ENUM('draft', 'educational_only', 'expert_reviewed', 'verified')
        NOT NULL DEFAULT 'educational_only',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX idx_fertilizer_crop_stage ON fertilizer_recommendations(crop_name, growth_stage);


-- ==============================================================================
-- Table E: uploads (Phase 2)
-- Stores metadata for securely uploaded leaf images prior to AI inference.
-- Retains pre-analysis image characteristics without fabricating predictions.
-- ==============================================================================
CREATE TABLE IF NOT EXISTS uploads (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    upload_id VARCHAR(64) NOT NULL UNIQUE,
    stored_filename VARCHAR(255) NOT NULL,
    original_filename VARCHAR(255) NULL,
    relative_path VARCHAR(255) NOT NULL,
    mime_type VARCHAR(50) NOT NULL,
    file_size INT UNSIGNED NOT NULL,
    image_width INT UNSIGNED NOT NULL,
    image_height INT UNSIGNED NOT NULL,
    status ENUM('uploaded', 'pending_analysis', 'analyzed', 'failed')
        NOT NULL DEFAULT 'pending_analysis',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX idx_uploads_upload_id ON uploads(upload_id);
CREATE INDEX idx_uploads_created_at ON uploads(created_at);
CREATE INDEX idx_uploads_status ON uploads(status);
